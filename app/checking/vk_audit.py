"""Targeted engineering audit prompts for Project Expert AI.

The visual model is used to extract concrete project facts. Normative
compliance is decided only after RAG retrieval against indexed SP text.
"""
from __future__ import annotations

VK_AUDIT_CHECKS = [
    ("расчётные расходы воды", "максимальные секундные и часовые расходы, таблицы расчётов, исходные расходы"),
    ("диаметры водопровода", "диаметры вводов, магистралей, стояков и подводок"),
    ("приборы учёта", "водомерные узлы, счётчики и параметры узлов учёта на вводах"),
    ("поливочные краны", "поливочные краны и точки разбора воды, если они предусмотрены объектом"),
    ("канализационные расходы", "расчётные расходы бытовой канализации и исходные данные"),
    ("диаметры и уклоны канализации", "диаметры канализационных труб и значения уклонов"),
    ("вентиляция канализации", "вентиляционные стояки, вытяжные части и выводы"),
    ("аварийные выпуски", "аварийные выпуски внутренних систем"),
    ("материал труб", "марка, материал труб, область применения, давление и температура"),
    ("шумоизоляция стояков", "мероприятия по снижению шума и вибрации"),
    ("разделение канализации", "хозяйственно-бытовая, производственная и дождевой канализации"),
    ("согласование с архитектурой", "санитарные приборы, помещения, стояки и точки подключения"),
]


def build_vk_audit_prompt(page_number: int) -> str:
    checks = "\n".join(f"- {name}: {details}" for name, details in VK_AUDIT_CHECKS)
    return f"""Ты выполняешь инженерный первичный аудит страницы PDF №{page_number} раздела ВК.

Цель — извлечь из страницы структурированные факты проекта для последующей проверки по СП 30, СП 31 и СП 32. Самостоятельно нарушение не объявляй.

ЧЕК-ЛИСТ:
{checks}

Особенно важно извлекать данные из таблиц и схем в исходном виде. Если на странице есть строка таблицы, возвращай её как отдельный факт, сохраняя обозначение параметра, числовое значение, единицу измерения и контекст строки.

Правила:
1. Возвращай только реально видимые факты этой страницы.
2. Не угадывай значения, единицы, номера пунктов и отсутствующие элементы.
3. Для каждого количественного факта обязательно отделяй project_value и unit от evidence_text.
4. parameter — короткое имя проверяемого параметра: например «диаметр стояка», «уклон», «расход воды», «число санитарных приборов».
5. source_row — текст строки/позиции таблицы или подписи схемы в максимально исходном виде.
6. Если виден номер таблицы, обозначение стояка или помещения — сохрани его в source_context.
7. bbox должен охватывать именно строку/ячейку/обозначение, а не пустую область.
8. evidence_text должен быть точным видимым фрагментом.
9. Не создавай кандидата только по штампу, рамке, названию листа или декоративному тексту.
10. Несколько строк одной таблицы допускаются и предпочтительны, если они содержат разные проверяемые значения.

Верни только JSON-массив:
[{{"title":"конкретный факт","description":"что видно и что проверяется","parameter":"","project_value":"","unit":"","source_row":"","source_context":"","evidence_text":"точный видимый фрагмент","bbox":[x1,y1,x2,y2],"confidence":0.0}}]
Если полезных фактов нет — []."""

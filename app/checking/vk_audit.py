"""Skill-driven visual evidence extraction for engineering audits."""
from __future__ import annotations

from app.skills.registry import get_skill
from app.skills.vk_wastewater_report import VK_ALWAYS_REJECT_AS_STANDALONE, VK_HIGH_VALUE_SIGNALS, VK_REPORT_SPEC


def build_vk_audit_prompt(page_number: int, skill_id: str = "vk_wastewater") -> str:
    """Build one page-level extraction contract covering the complete Skill checklist.

    The vision model performs one pass per PDF page, but every observation must be
    assigned to one of the Skill's explicit checks. This prevents the pipeline from
    treating arbitrary OCR numbers as independent checks while keeping the number
    of expensive vision calls bounded by the number of PDF pages.
    """
    skill = get_skill(skill_id)
    checks = "\n".join(
        f"- {item['id']}: {item['name']} — {', '.join(item.get('parameters', []))}"
        for item in skill["checks"]
    )
    signals = "\n".join(f"- {key}: {', '.join(values)}" for key, values in VK_HIGH_VALUE_SIGNALS.items())
    reject = ", ".join(VK_ALWAYS_REJECT_AS_STANDALONE)
    return f"""Ты — эксперт по нормоконтролю раздела ВК. Выполняешь ТОЛЬКО первичный сбор доказательств со страницы PDF №{page_number}.

ПРОФИЛЬ: {skill['name']} ({skill['code']})

АРХИТЕКТУРА ПРОВЕРКИ:
Эта страница является частью ОДНОГО аудита по всем {len(skill['checks'])} проверкам Skill. Не создавай отдельную проверку для каждого числа. Сначала определи, к какой конкретной проверке Skill относится наблюдаемый факт, и только затем верни один кандидат.

ЧЕК-ЛИСТ — ЭТО ЕДИНСТВЕННЫЕ ДОПУСТИМЫЕ ПРЕДМЕТЫ ПРОВЕРКИ:
{checks}

ВЫСОКОЦЕННЫЕ СИГНАЛЫ:
{signals}

ПРАВИЛА ЭКСПЕРТНОГО ОТБОРА:
1. Каждый кандидат ОБЯЗАН иметь check_id ровно из приведённого чек-листа.
2. Один кандидат = один предмет инженерной проверки, а не отдельное случайное число.
3. Не возвращай кандидатов только потому, что на странице есть число, Ø, i, марка или слово.
4. Сохраняй project_value БУКВАЛЬНО, как он виден в проекте.
5. evidence_text должен содержать достаточный контекст: строку таблицы, подпись элемента, обозначение системы, диаметр+систему, уклон+диаметр, расчётный показатель и т.п.
6. Для диаметра обязательно указывай систему/участок. «Ø100» без контекста — НЕ кандидат.
7. Для уклона обязательно связывай i с трубой/системой/диаметром. «i=0.000» само по себе — НЕ кандидат.
8. Для материала обязательно указывай, какие именно трубы и на каком участке. Марка стали/футляра без связи с проверяемой канализационной трубой — НЕ кандидат.
9. Для вентиляции требуется явная связь с канализационным стояком/фановой частью/выходом выше кровли. Любая надпись на схеме не считается вентиляцией.
10. Для приборов учёта ищи именно водомер/счётчик/узел учёта. Пожаротушение, насосы, арматура и оборудование не являются прибором учёта.
11. Для аварийных решений ищи именно аварийный выпуск/сброс и его контекст. Обычный выпуск К1/К2 не объявляй аварийным без явного признака.
12. Для поливочных устройств нужен явный поливочный кран/устройство и контекст его применения.
13. Для кросс-сверки с АР извлекай санитарные приборы только с однозначным количеством/типом/помещением; само сравнение выполняется отдельным документным этапом.
14. Для проверок «наличие/отсутствие» не утверждай отсутствие по одной странице. Возвращай только фактически наблюдаемые решения/элементы; итоговая проверка отсутствия выполняется после просмотра всего документа.
15. Не превращай название листа, обозначение проекта, номер страницы, штамп или перечень нормативов в инженерное замечание.
16. Само наличие ссылки на старую редакцию СП — отдельный кандидат только если на странице явно указано, что она используется как нормативная база проекта.
17. Не создавай кандидатов из следующих строк, если рядом нет самостоятельного инженерного контекста: {reject}.
18. Не повторяй один и тот же факт несколько раз на одной странице. Если одинаковая строка встречается трижды, верни её один раз, если это не три разных участка.
19. Не создавай кандидата из дождевого расхода как хозяйственно-бытового канализационного расхода и не смешивай внутренний водосток с бытовой канализацией.
20. Не считай размер конструкции, ворот, футляра или металлоконструкции диаметром канализационной трубы.
21. Если факт не позволяет сформулировать конкретную проверку по одному из 13 пунктов — не возвращай его.

ТРЕБОВАНИЯ К ДОКАЗАТЕЛЬСТВУ:
- bbox только вокруг реального фрагмента, который должен попасть в доказательную картинку.
- bbox не должен покрывать пустую область, весь лист или крупный участок без нужного объекта.
- evidence_text должен быть достаточным для повторной проверки человеком.
- Один факт на странице — один кандидат; одинаковые кандидаты дедуплицируются сервером.

Верни ТОЛЬКО JSON-массив:
[{{"check_id":"один id из чек-листа","title":"предмет проверки","description":"какой конкретный факт виден и что именно проверяется","parameter":"","project_value":"","unit":"","source_row":"","source_context":"","evidence_text":"точный видимый фрагмент с достаточным контекстом","bbox":[x1,y1,x2,y2],"confidence":0.0}}]
Если на странице нет конкретных фактов по Skill — верни [].
"""

"""Skill-driven visual fact extraction for engineering audits."""
from __future__ import annotations

from app.skills.registry import get_skill


def build_vk_audit_prompt(page_number: int, skill_id: str = "vk_wastewater") -> str:
    """Build a page prompt from the selected expert skill, not a global checklist."""
    skill = get_skill(skill_id)
    checks = "\n".join(
        f"- {item['id']}: {item['name']} — {', '.join(item.get('parameters', []))}"
        for item in skill["checks"]
    )
    exclude = ", ".join(skill.get("extraction", {}).get("exclude", []))
    return f"""Ты выполняешь первичный инженерный аудит страницы PDF №{page_number}.

ПРОФИЛЬ ЭКСПЕРТИЗЫ: {skill['name']} ({skill['code']})
Цель — извлечь только реальные проектные факты, которые относятся к этому профилю. Нарушение самостоятельно не объявляй: нормативная проверка выполняется отдельным этапом.

ЧЕК-ЛИСТ ПРОФИЛЯ:
{checks}

Искать факты следует в тексте, таблицах, схемах и подписях элементов проекта. Для каждой найденной сущности укажи короткий parameter и сохрани исходный project_value. Если сегмент можно определить, укажи internal/external в source_context.

ЖЁСТКИЕ ОГРАНИЧЕНИЯ:
1. Возвращай только реально видимые факты этой страницы.
2. Не угадывай значения, единицы, номера пунктов и отсутствующие элементы.
3. Не создавай кандидата только потому, что на странице есть число, диаметр, размер или короткая строка.
4. Факт должен иметь явный инженерный контекст выбранного профиля: система, трубопровод, стояк, выпуск, прибор, расчёт, таблица или схема.
5. Не используй штампы, рамки, название листа, номер листа, подписи, колонтитулы и декоративный текст.
6. Не используй несвязанные элементы других разделов. В частности, строки вроде {exclude} сами по себе не являются доказательством проверки.
7. Для количественного факта отделяй project_value и unit от evidence_text.
8. source_row — исходная строка таблицы/позиция или подпись схемы; source_context — система, участок, стояк, помещение, таблица или иной контекст.
9. bbox должен охватывать именно строку, ячейку, обозначение или объект, подтверждающий факт, а не пустую область.
10. Один кандидат = один проверяемый факт. Не смешивай разные параметры в одном кандидате.
11. Если на странице нет фактов из чек-листа — верни []. Лучше вернуть меньше фактов, чем нерелевантный кандидат.

Верни только JSON-массив:
[{{"title":"конкретный факт","description":"что видно и к какой проверке относится","parameter":"","project_value":"","unit":"","source_row":"","source_context":"","evidence_text":"точный видимый фрагмент","bbox":[x1,y1,x2,y2],"confidence":0.0}}]
"""

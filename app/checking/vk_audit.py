"""Skill-driven visual fact extraction for engineering audits."""
from __future__ import annotations

from app.skills.registry import get_skill
from app.skills.vk_wastewater_report import VK_ALWAYS_REJECT_AS_STANDALONE, VK_HIGH_VALUE_SIGNALS, VK_REPORT_SPEC


def build_vk_audit_prompt(page_number: int, skill_id: str = "vk_wastewater") -> str:
    """Build a strict expert-style extraction contract for the selected Skill."""
    skill = get_skill(skill_id)
    checks = "\n".join(
        f"- {item['id']}: {item['name']} — {', '.join(item.get('parameters', []))}"
        for item in skill["checks"]
    )
    signals = "\n".join(f"- {key}: {', '.join(values)}" for key, values in VK_HIGH_VALUE_SIGNALS.items())
    reject = ", ".join(VK_ALWAYS_REJECT_AS_STANDALONE)
    return f"""Ты — эксперт по нормоконтролю раздела ВК. Выполняешь ТОЛЬКО первичный сбор доказательств со страницы PDF №{page_number}.

ПРОФИЛЬ: {skill['name']} ({skill['code']})

ВАЖНО: твоя задача не перечислять всё, что есть на чертеже. Твоя задача — найти факты, из которых реально может получиться экспертное замечание после проверки по СП. Чем меньше нерелевантных кандидатов, тем лучше.

ЧЕК-ЛИСТ:
{checks}

ВЫСОКОЦЕННЫЕ СИГНАЛЫ:
{signals}

ПРАВИЛА ЭКСПЕРТНОГО ОТБОРА:
1. Кандидат допускается только при наличии явной связи с одной из проверок чек-листа.
2. Один кандидат = один потенциальный предмет проверки, а не отдельное случайное слово/число.
3. Сохраняй project_value БУКВАЛЬНО, как он виден в проекте.
4. evidence_text должен содержать достаточный контекст: строку таблицы, подпись элемента, обозначение системы, диаметр+систему, уклон+диаметр, расчётный показатель и т.п.
5. Для диаметра обязательно указывай систему/участок. «Ø100» без контекста — НЕ кандидат.
6. Для уклона обязательно связывай i с трубой/системой/диаметром. «i=0.000» само по себе — НЕ кандидат.
7. Для материала обязательно указывай, какие именно трубы и на каком участке. Марка стали/футляра без связи с проверяемой канализационной трубой — НЕ кандидат.
8. Для вентиляции требуется явная связь с канализационным стояком/фановой частью/выходом выше кровли. Любая надпись на схеме не считается вентиляцией.
9. Для приборов учёта ищи именно водомер/счётчик/узел учёта. Пожаротушение, насосы, арматура и оборудование не являются прибором учёта.
10. Для аварийных решений ищи именно аварийный выпуск/сброс и его контекст. Обычный выпуск K1/K2 не объявляй аварийным без явного признака.
11. Для поливочных устройств нужен явный поливочный кран/устройство и контекст его применения.
12. Для кросс-сверки с АР извлекай санитарные приборы только с однозначным количеством/типом/помещением; сравнение выполняется отдельным этапом.
13. Не превращай название листа, обозначение проекта, номер страницы, штамп или перечень нормативов в инженерное замечание.
14. Само наличие ссылки на старую редакцию СП — отдельный кандидат только если на странице это явно указано как применяемая нормативная база проекта; не связывай такую строку с произвольным другим СП.
15. Не создавай кандидатов из следующих строк, если рядом нет самостоятельного инженерного контекста: {reject}.
16. Не повторяй один и тот же факт несколько раз на одной странице. Если одинаковая строка встречается трижды, верни её один раз, если только это действительно три разных участка.
17. Не создавай кандидата из дождевого расхода как хозяйственно-бытового канализационного расхода и не смешивай внутренний водосток с бытовой канализацией.
18. Не считай размер конструкции, ворот, футляра или металлоконструкции диаметром канализационной трубы.
19. Если факт не позволяет сформулировать конкретную проверку по одному из пунктов чек-листа — верни [].

ТРЕБОВАНИЯ К ДОКАЗАТЕЛЬСТВУ:
- bbox только вокруг реального фрагмента, который должен попасть в доказательную картинку.
- bbox не должен покрывать пустую область, весь лист или крупный участок без нужного объекта.
- Для замечания позже должна существовать связь: номер замечания N -> изображение N.

ЦЕЛЕВАЯ СТРУКТУРА БУДУЩЕГО ОТЧЁТА:
{', '.join(VK_REPORT_SPEC['sections'])}
Каждое подтверждённое замечание должно содержать: номер, предметное название, лист, страницу PDF, параметр, буквальное значение в исходнике, точное нормативное требование, СП, пункт, доказательное описание, конкретную рекомендацию и один доказательный фрагмент.

Верни ТОЛЬКО JSON-массив:
[{{"title":"предмет проверки","description":"что именно видно и почему это является предметом проверки","parameter":"","project_value":"","unit":"","source_row":"","source_context":"","evidence_text":"точный видимый фрагмент с достаточным контекстом","bbox":[x1,y1,x2,y2],"confidence":0.0}}]
"""

"""Targeted engineering audit prompts for Project Expert AI.

The visual model is not asked to invent violations. It is given a concrete
VК checklist and must return only page regions containing visible evidence.
The checklist is a search plan, not a normative source; every candidate is
validated against the indexed СП/ГОСТ text afterwards.
"""
from __future__ import annotations

VK_AUDIT_CHECKS = [
    ("расчётные расходы воды", "расчётные расходы воды, максимальные секундные и часовые расходы, таблицы расчётов"),
    ("диаметры водопровода", "диаметры вводов, магистралей, стояков и подводок, видимые в таблицах и схемах"),
    ("приборы учёта", "водомерные узлы, счётчики, узлы учёта на вводах и их параметры"),
    ("поливочные краны", "поливочные краны и точки разбора воды, если они предусмотрены объектом"),
    ("канализационные расходы", "расчётные расходы бытовой канализации и исходные данные для расчёта"),
    ("диаметры и уклоны канализации", "диаметры канализационных труб и указанные уклоны i"),
    ("вентиляция канализации", "вентиляционные стояки, вытяжные части, выводы и их связь со схемой канализации"),
    ("аварийные выпуски", "аварийные выпуски внутренних систем, если требуются для объекта"),
    ("материал труб", "марка и материал труб, область применения, давление/температура и обоснование выбора"),
    ("шумоизоляция стояков", "мероприятия по снижению шума и вибрации стояков и трубопроводов"),
    ("разделение канализации", "разделение хозяйственно-бытовой, производственной и дождевой канализации там, где это применимо"),
    ("согласование с архитектурой", "санитарные приборы, помещения, стояки и точки подключения, которые можно сопоставить с планом"),
]


def build_vk_audit_prompt(page_number: int) -> str:
    checks = "\n".join(f"- {name}: {details}" for name, details in VK_AUDIT_CHECKS)
    return f"""Ты выполняешь инженерный первичный аудит страницы PDF №{page_number} раздела ВК.

Цель — найти конкретные факты, которые затем будут строго сопоставлены с текстом СП 30, СП 31 и СП 32. Не объявляй нарушение самостоятельно.

ЧЕК-ЛИСТ АУДИТА:
{checks}

Правила кандидата:
1. Возвращай только то, что реально видно на этой странице: число, диаметр, уклон, расход, таблицу, обозначение, схему, прибор, текст требования проекта или конкретное отсутствие ожидаемого элемента в видимой таблице/схеме.
2. Если утверждение об отсутствии относится ко всему проекту, но на этой странице это нельзя доказать, НЕ создавай кандидата.
3. Для отсутствующего расчёта указывай bbox на таблицу/схему/проектное значение, отсутствие которого проверяется, а НЕ на пустое белое поле.
4. bbox задавай в координатах изображения 0..1: [x1,y1,x2,y2]. Это обязательно.
5. evidence_text должен содержать точный видимый текст или значение из выделенной области.
6. Не возвращай только название листа, номер документа, рамку, штамп или декоративный текст.
7. Не возвращай кандидата, если не можешь указать конкретный видимый факт.
8. Допускается несколько кандидатов на странице, но только существенные инженерные факты.

Верни только JSON-массив:
[{{"title":"конкретный факт проверки","description":"что именно видно и что требуется проверить","evidence_text":"точный видимый фрагмент","bbox":[x1,y1,x2,y2],"confidence":0.0}}]
Если на странице нет полезных фактов — []."""
